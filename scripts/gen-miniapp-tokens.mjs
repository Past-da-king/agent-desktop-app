#!/usr/bin/env node
/**
 * Writes apps/desktop/src/shared/miniapp-tokens.ts from the renderer's tokens.css, the one source of the app's look.
 * Mini-apps (main/miniapps) are served these very tokens. test/miniapp-kit.test.ts fails when the two differ.
 *   node scripts/gen-miniapp-tokens.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const css = readFileSync(join(root, 'apps/desktop/src/renderer/styles/tokens.css'), 'utf8').replace(/\r\n/g, '\n')
const out = [
  '/**',
  ' * GENERATED by scripts/gen-miniapp-tokens.mjs from renderer/styles/tokens.css. Do not edit: change tokens.css and run it.',
  ' * The design tokens every mini-app is served (main/miniapps/protocol.ts), so an app looks exactly like the app.',
  ' */',
  `export const TOKENS_CSS = ${JSON.stringify(css)}`,
  '',
].join('\n')
writeFileSync(join(root, 'apps/desktop/src/shared/miniapp-tokens.ts'), out)
console.log('wrote shared/miniapp-tokens.ts', css.length, 'chars')
